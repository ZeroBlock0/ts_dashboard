# Global current language
_current_lang = "zh_CN"

def init_language():
    global _current_lang
    config = load_config()
    _current_lang = config.get("language", "zh_CN")

def tr(key):
    """Translate a key to the current language."""
    return TRANSLATIONS.get(_current_lang, TRANSLATIONS["zh_CN"]).get(key, key)

def get_current_language():
    return _current_lang
